import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { mkdtempSync, cpSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { buildCues, cueText } from "../captions-from-transcript.mjs";

const script = fileURLToPath(new URL("../captions-from-transcript.mjs", import.meta.url));
const fx = fileURLToPath(new URL("./fixtures/captions-bds", import.meta.url));
const load = (f) => JSON.parse(readFileSync(join(fx, f), "utf8"));

test("reproduces the real-estate project's approved captions from transcript + fixes", () => {
  const cues = buildCues(load("transcript.json"), load("captions.fixes.json"), { duration: 60.18 });
  assert.deepEqual(cues, load("expected-cues.json"));
});

test("unclear spans are never captioned; fix \"\" drops a word", () => {
  const cues = buildCues(load("transcript.json"), load("captions.fixes.json"), { duration: 60.18 });
  const all = cues.map(cueText).join(" ");
  assert.ok(!/tạc xã|Bên hông/.test(all));
  assert.ok(all.includes("Đây, đất phía bên này") && !all.includes("gặp phía"));
});

test("auto grouping without ranges: no one-word cues on the real transcript, ≤ 7 words each", () => {
  const fixes = load("captions.fixes.json");
  delete fixes.ranges;
  const cues = buildCues(load("transcript.json"), fixes, { duration: 60.18 });
  assert.ok(cues.length > 10);
  assert.ok(cues.every((c) => c.words.length <= 7));
  assert.ok(cues.filter((c) => c.words.length === 1).length <= 2, cues.filter((c) => c.words.length === 1).map(cueText).join("|"));
});

test("CLI writes captions.js, script/captions.txt and captions.review.md", () => {
  const dir = mkdtempSync(join(tmpdir(), "cap-"));
  try {
    cpSync(join(fx, "transcript.json"), join(dir, "transcript.json"));
    cpSync(join(fx, "captions.fixes.json"), join(dir, "captions.fixes.json"));
    const r = spawnSync("node", [script, "--project", dir, "--global", "BDS_CAPTIONS", "--duration", "60.18"], { encoding: "utf8" });
    assert.equal(r.status, 0, r.stderr);
    const js = readFileSync(join(dir, "assets/fx/captions.js"), "utf8");
    assert.match(js, /^\/\/ Generated by opus-video/);
    assert.match(js, /window\.BDS_CAPTIONS = \[/);
    assert.equal(readFileSync(join(dir, "script/captions.txt"), "utf8").split("\n")[0], "Dạ đây, đây là chợ Diên An.");
    const review = readFileSync(join(dir, "captions.review.md"), "utf8");
    assert.match(review, /\| 5 \| 1\.82 \| Duyên \| Diên \|/);
    assert.match(review, /chưa rõ, không phụ đề/);
    writeFileSync(join(dir, "captions.fixes.json"), "{bad json");
    assert.equal(spawnSync("node", [script, "--project", dir], { encoding: "utf8" }).status, 2);
  } finally { rmSync(dir, { recursive: true, force: true }); }
});
